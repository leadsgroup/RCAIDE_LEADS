def create_interpolator(prompt):
    """
    Parses the CSV string and builds the interpolator ONCE.
    """
    # Parse data
    if prompt == "table_c1":
        csv_data = table1_full
    if prompt == "table_c2":
        csv_data = table2_full
    if prompt == "table_c3":
        csv_data = table3_full
    df = pd.read_csv(io.StringIO(csv_data.strip()), index_col=0)
    
    # Safety check
    if df.empty or df.shape[1] == 0:
        raise ValueError("DataFrame is empty. Check the formatting of your CSV string.")
    
    # Extract grid axes
    angles = np.array([float(c) for c in df.columns]) # X-axis
    log_strouhal = df.index.values # Y-axis
    spl_matrix = df.values # Z-data
    
    # RegularGridInterpolator strictly requires monotonically increasing axes.
    sort_x = np.argsort(angles)
    sort_y = np.argsort(log_strouhal)
    
    angles_sorted = angles[sort_x]
    log_strouhal_sorted = log_strouhal[sort_y]
    
    # Sort the Z-matrix to match the new sorted axes
    spl_matrix_sorted = spl_matrix[sort_y, :][:, sort_x]
    
    # Create and return the interpolator
    return RegularGridInterpolator(
        (log_strouhal_sorted, angles_sorted), 
        spl_matrix_sorted, 
        method='linear', 
        bounds_error=False, 
        fill_value=None
    )

def get_spl(interpolator, angle, logsc):
    """
    Queries the pre-built interpolator.
    """
    # The double brackets [[ ]] ensure the input is shape (1, 2).
    # This guarantees the output is a 1D array of shape (1,), making result[0] perfectly safe.
    result = interpolator(np.array([[logsc, angle]]))
    
    # Handle NaN values if the point is out of bounds
    if np.isnan(result[0]):
        return 0.0 # Or apply a custom extrapolation rule
        
    return float(result[0])
