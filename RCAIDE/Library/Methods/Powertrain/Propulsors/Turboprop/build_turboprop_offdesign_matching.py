# RCAIDE imports
from RCAIDE.Framework.Core                                                                import Data, Units
from RCAIDE.Library.Methods.Powertrain.Propulsors.Turboprop.design_turboprop_offdesign_matching import design_turboprop_offdesign_matching
from RCAIDE.Library.Methods.Powertrain.Propulsors.Turboprop.generate_turboprop_deck          import generate_turboprop_deck
from RCAIDE.Library.Methods.Powertrain.Propulsors.Turbofan.Turbofan_Surrogate                import Turbofan_Surrogate

# Python package imports
import numpy as np

# ----------------------------------------------------------------------------------------------------------------------
#  build_turboprop_offdesign_matching
# ----------------------------------------------------------------------------------------------------------------------
def build_turboprop_offdesign_matching(turboprop, combustor_exit_temperature_fractions=[1.0, 0.9, 0.8, 0.7, 0.6, 0.5, 0.4],
                                       number_of_altitudes=10, number_of_mach_numbers=10):
    """
    Builds the off-design matching model used by compute_turboprop_performance: the design constants
    and reference point of an already-sized turboprop, plus an idle_fallback surrogate for operating
    points where the matching solver does not converge.

    Parameters
    ----------
    turboprop : RCAIDE.Library.Components.Powertrain.Propulsors.Turboprop
        Turboprop already sized by design_turboprop's design-point cycle solve, with
        turboprop.offdesign_matching still None.
    combustor_exit_temperature_fractions : list of float, optional
        Fractions of the design combustor exit stagnation temperature swept to build the
        idle_fallback deck.
    number_of_altitudes : int, optional
        Number of altitudes, from sea level to the larger of the design altitude and 30,000 ft,
        in the idle_fallback deck.
    number_of_mach_numbers : int, optional
        Number of Mach numbers, from 0 to the larger of the design Mach number and 0.65, in the
        idle_fallback deck.

    Returns
    -------
    offdesign_matching : Data
        design_constants, reference_point and idle_fallback, as consumed by
        compute_turboprop_performance_offdesign.

    Notes
    -----
    Same construction as build_turbofan_offdesign_matching: the idle_fallback deck is generated by
    the turboprop's own off-design matching solver, points it cannot converge are omitted, and the
    surrogate extrapolates smoothly below the lowest converged throttle.

    See Also
    --------
    RCAIDE.Library.Methods.Powertrain.Propulsors.Turbofan.build_turbofan_offdesign_matching
    """
    design_constants, reference_point = design_turboprop_offdesign_matching(turboprop)

    maximum_altitude    = max(turboprop.design_altitude, 30000. * Units.ft)
    maximum_mach_number = max(float(np.ravel(turboprop.design_mach_number)[0]), 0.65)
    altitude_range      = np.linspace(0.0, maximum_altitude, number_of_altitudes)
    mach_range          = np.concatenate([[0.0], np.linspace(0.1, maximum_mach_number, number_of_mach_numbers - 1)])

    decks = []
    for fraction in combustor_exit_temperature_fractions:
        deck_fraction                   = generate_turboprop_deck(turboprop, altitude_range, mach_range,
                                                                  combustor_exit_temperature=fraction * reference_point.Tt4)
        deck_fraction.throttle_fraction = np.full(len(deck_fraction.altitude_m), fraction)
        decks.append(deck_fraction)

    deck = Data()
    for field in ['altitude_m', 'mach_number', 'thrust_N', 'fuel_mass_flow_rate', 'isa_deviation_k', 'rating_code', 'throttle_fraction']:
        deck[field] = np.concatenate([deck_fraction[field] for deck_fraction in decks])
    idle_fallback = Turbofan_Surrogate().build(deck=deck)

    offdesign_matching = Data(design_constants = design_constants,
                              reference_point  = reference_point,
                              idle_fallback    = idle_fallback)
    return offdesign_matching
