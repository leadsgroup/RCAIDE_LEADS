# RCAIDE imports
from RCAIDE.Framework.Core                                                              import Data
from RCAIDE.Library.Methods.Powertrain.Propulsors.Turbofan.design_turbofan_offdesign_matching import design_turbofan_offdesign_matching
from RCAIDE.Library.Methods.Powertrain.Propulsors.Turbofan.generate_turbofan_deck          import generate_turbofan_deck
from RCAIDE.Library.Methods.Powertrain.Propulsors.Turbofan.Turbofan_Surrogate              import Turbofan_Surrogate

# Python package imports
import numpy as np

# ----------------------------------------------------------------------------------------------------------------------
#  build_turbofan_offdesign_matching
# ----------------------------------------------------------------------------------------------------------------------
def build_turbofan_offdesign_matching(turbofan, combustor_exit_temperature_fractions=[1.0, 0.9, 0.8, 0.7, 0.6, 0.5, 0.4],
                                      number_of_altitudes=10, number_of_mach_numbers=10):
    """
    Builds the off-design matching model used by compute_turbofan_performance: the design constants
    and reference point of an already-sized turbofan, plus an idle_fallback surrogate for operating
    points where the matching solver does not converge.

    Parameters
    ----------
    turbofan : RCAIDE.Library.Components.Powertrain.Propulsors.Turbofan
        Turbofan already sized by design_turbofan's design-point cycle solve, with
        turbofan.offdesign_matching still None.
    combustor_exit_temperature_fractions : list of float, optional
        Fractions of the design combustor exit stagnation temperature swept to build the
        idle_fallback deck.
    number_of_altitudes : int, optional
        Number of altitudes, from sea level to the design altitude, in the idle_fallback deck.
    number_of_mach_numbers : int, optional
        Number of Mach numbers, from 0 to the design Mach number, in the idle_fallback deck.

    Returns
    -------
    offdesign_matching : Data
        design_constants, reference_point and idle_fallback, as consumed by
        compute_turbofan_performance_offdesign.

    Notes
    -----
    The idle_fallback deck is generated by the off-design matching solver itself, so it is
    consistent with the live solution wherever the two overlap. Points the solver cannot converge
    (deep part power) are omitted from the deck and the surrogate extrapolates smoothly below the
    lowest converged throttle, which keeps a nonzero thrust gradient for the mission trim solver.
    Nozzle and fan station states are not available at points routed to idle_fallback (NaN).

    See Also
    --------
    RCAIDE.Library.Methods.Powertrain.Propulsors.Turbofan.design_turbofan_offdesign_matching
    RCAIDE.Library.Methods.Powertrain.Propulsors.Turbofan.generate_turbofan_deck
    """
    design_constants, reference_point = design_turbofan_offdesign_matching(turbofan)

    altitude_range = np.linspace(0.0, turbofan.design_altitude, number_of_altitudes)
    mach_range     = np.concatenate([[0.0], np.linspace(0.1, turbofan.design_mach_number, number_of_mach_numbers - 1)])

    decks = []
    for fraction in combustor_exit_temperature_fractions:
        deck_fraction                   = generate_turbofan_deck(turbofan, altitude_range, mach_range,
                                                                 combustor_exit_temperature=fraction * reference_point.Tt4)
        deck_fraction.throttle_fraction = np.full(len(deck_fraction.altitude_m), fraction)
        decks.append(deck_fraction)

    deck = Data()
    for field in ['altitude_m', 'mach_number', 'thrust_N', 'fuel_mass_flow_rate', 'isa_deviation_k', 'rating_code', 'throttle_fraction']:
        deck[field] = np.concatenate([deck_fraction[field] for deck_fraction in decks])
    idle_fallback = Turbofan_Surrogate().build(deck=deck)

    offdesign_matching = Data(design_constants = design_constants,
                              reference_point  = reference_point,
                              idle_fallback    = idle_fallback)
    return offdesign_matching
